#!/bin/sh

# 20261027: generate USB string descriptor names for products whose names must not be committed
# before launch. Called from Makefile for FEATURE_PRODUCT_OEM01, output goes to src/product_names_local.h.
# 20261105: after each build the Makefile calls it again with "Manufacturer" "Product", so the header in git
# only ever holds generic names. Usage:
#   sh ./make-names.sh "Manufacturer name" "Product name" > src/product_names_local.h
#
# USB string descriptors are UTF-16. Each character becomes one Usb_unicode('c'), so use plain ASCII.
# The characters ' " \ $ and ` are rejected.

for name in "$1" "$2"
do
	if [ -z "$name" ]
	then
		echo "make-names.sh: manufacturer and product names are both required" 1>&2
		exit 1
	fi
	case "$name" in
		*\'* | *\"* | *\\* | *\$* | *\`*)
			echo "make-names.sh: name \"$name\" contains one of ' \" \\ \$ \`" 1>&2
			exit 1
		;;
	esac
done

# One Usb_unicode() per character
unicode_list() {
	printf '%s' "$1" | sed -e "s/./Usb_unicode('&'), /g"
}

echo "/* Generated by make-names.sh - do not edit. Reset to generic names after each build, see Makefile */"
echo "#ifndef PRODUCT_NAMES_LOCAL_H_"
echo "#define PRODUCT_NAMES_LOCAL_H_"
echo "#define USB_MN_LENGTH ${#1}"
echo "#define USB_MANUFACTURER_NAME { $(unicode_list "$1") }"
echo "#define USB_PN_LENGTH ${#2}"
echo "#define USB_PRODUCT_NAME { $(unicode_list "$2") }"
echo "#endif"
